-- Jalankan seluruh SQL ini di Supabase Dashboard > SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
drop policy if exists profiles_self on public.profiles;
drop policy if exists profiles_read_username on public.profiles;
create policy profiles_self on public.profiles
  for all
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, username)
  values (
    new.id,
    lower(coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)))
  )
  on conflict (id) do update set username = excluded.username;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  owner_key text,
  owner_id uuid references auth.users(id) on delete cascade,
  owner_email text,
  expense_date date not null,
  name text not null,
  category text not null,
  amount numeric(14, 2) not null check (amount > 0),
  created_at timestamptz not null default now()
);

create index if not exists expenses_owner_date_idx
  on public.expenses (owner_key, expense_date desc);

alter table public.expenses add column if not exists owner_id uuid references auth.users(id) on delete cascade;
alter table public.expenses add column if not exists owner_email text;

create table if not exists public.expense_limits (
  owner_key text,
  owner_id uuid references auth.users(id) on delete cascade,
  month_key text not null,
  amount numeric(14, 2) not null check (amount > 0),
  updated_at timestamptz not null default now(),
  primary key (owner_key, month_key)
);

-- owner_key menyimpan UID untuk akun baru, sehingga tetap kompatibel dengan
-- primary key lama dan dapat digunakan sebagai konflik saat upsert.

alter table public.expense_limits add column if not exists owner_id uuid references auth.users(id) on delete cascade;

-- Migrasi data lama: owner_key berisi username, owner_id berisi UID Supabase Auth.
update public.expenses e
set owner_id = p.id
from public.profiles p
where e.owner_id is null and lower(e.owner_key) = lower(p.username);

update public.expenses e
set owner_email = u.email
from auth.users u
where e.owner_id = u.id;

create or replace function public.set_expense_owner_email()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  if new.owner_id is null then
    new.owner_id := auth.uid();
  end if;
  select u.email into new.owner_email
  from auth.users u
  where u.id = new.owner_id;
  return new;
end;
$$;

drop trigger if exists set_expense_owner_email on public.expenses;
create trigger set_expense_owner_email
before insert or update on public.expenses
for each row execute function public.set_expense_owner_email();

update public.expense_limits l
set owner_id = p.id
from public.profiles p
where l.owner_id is null and lower(l.owner_key) = lower(p.username);

alter table public.expenses enable row level security;
alter table public.expense_limits enable row level security;

-- Hapus policy lama agar SQL dapat dijalankan ulang tanpa konflik nama policy.
drop policy if exists expenses_public on public.expenses;
drop policy if exists expense_limits_public on public.expense_limits;
drop policy if exists expenses_owner on public.expenses;
drop policy if exists expense_limits_owner on public.expense_limits;

create policy expenses_owner
  on public.expenses
  for all
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

create policy expense_limits_owner
  on public.expense_limits
  for all
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);
   