-- Jalankan seluruh SQL ini di Supabase Dashboard > SQL Editor.

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  owner_key text,
  owner_id uuid references auth.users(id) on delete cascade,
  expense_date date not null,
  name text not null,
  category text not null,
  amount numeric(14, 2) not null check (amount > 0),
  created_at timestamptz not null default now()
);

create index if not exists expenses_owner_date_idx
  on public.expenses (owner_key, expense_date desc);

alter table public.expenses add column if not exists owner_id uuid references auth.users(id) on delete cascade;

create table if not exists public.expense_limits (
  owner_key text,
  owner_id uuid references auth.users(id) on delete cascade,
  month_key text not null,
  amount numeric(14, 2) not null check (amount > 0),
  updated_at timestamptz not null default now(),
  primary key (owner_key, month_key)
);

-- owner_key menyimpan UID untuk akun baru, sehingga tetap kompatibel dengan
-- primary key lama dan dapat digunakan sebagai konflik saat upsert.

alter table public.expense_limits add column if not exists owner_id uuid references auth.users(id) on delete cascade;

alter table public.expenses enable row level security;
alter table public.expense_limits enable row level security;

-- Hapus policy lama agar SQL dapat dijalankan ulang tanpa konflik nama policy.
drop policy if exists expenses_public on public.expenses;
drop policy if exists expense_limits_public on public.expense_limits;
drop policy if exists expenses_owner on public.expenses;
drop policy if exists expense_limits_owner on public.expense_limits;

create policy expenses_owner
  on public.expenses
  for all
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

create policy expense_limits_owner
  on public.expense_limits
  for all
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);
   