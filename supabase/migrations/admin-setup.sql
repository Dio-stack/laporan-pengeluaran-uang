-- =====================================================
-- ADMIN PANEL DATABASE SETUP
-- =====================================================
-- Jalankan script ini di Supabase Dashboard > SQL Editor
-- Script ini membuat tabel yang dibutuhkan oleh admin panel
-- =====================================================

-- 1. TABEL ADMIN (hanya user yang ditunjuk yang bisa akses admin panel)
create table if not exists public.admins (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  email text not null unique,
  is_superadmin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.admins enable row level security;

-- Policy: user bisa baca/update data diri sendiri
create policy admins_self on public.admins
  for all
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

-- 2. TABEL TRACKING USAGE AI (untuk monitoring kuota)
create table if not exists public.ai_usage_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  request_date date not null,
  tokens_used integer not null default 0,
  model_used text,
  status text,  -- 'success' atau 'failed'
  error_message text,
  created_at timestamptz not null default now()
);

alter table public.ai_usage_logs enable row level security;

-- Index untuk performa query per tanggal
create index if not exists ai_usage_logs_date_idx
  on public.ai_usage_logs (user_id, request_date desc);

-- Policy: SEMUA user yang login bisa INSERT (track usage mereka sendiri)
create policy ai_usage_user_insert on public.ai_usage_logs
  for insert
  with check ((select auth.uid()) = user_id);

-- Policy: HANYA ADMIN yang bisa SELECT (lihat data semua user)
create policy ai_usage_admin_select on public.ai_usage_logs
  for select
  using (
    exists (
      select 1 from public.admins a
      where a.id = (select auth.uid())
    )
  );

-- Policy: HANYA ADMIN yang bisa delete
create policy ai_usage_admin_delete on public.ai_usage_logs
  for delete
  using (
    exists (
      select 1 from public.admins a
      where a.id = (select auth.uid())
    )
  );

